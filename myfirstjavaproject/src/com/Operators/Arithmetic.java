package com.Operators;

public class Arithmetic {

	public static void main(String[] args) {
     System.out.println("sub: "+ (10-20));
     int result=20;
     System.out.println(result+=20);//40
     System.out.println(result-=20);//20
     System.out.println(result*=2);//40
     System.out.println(result/=2);//20
     System.out.println(result%=3);//2
     
	}

}
